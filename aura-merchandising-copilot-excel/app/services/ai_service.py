def _is_model_identity_question(message: str) -> bool:
    """Recognize common questions about which model/provider powers the app."""
    text = re.sub(r"[^a-z0-9]+", " ", (message or "").lower()).strip()
    patterns = (
        r"\bwhich model\b",
        r"\bwhat model\b",
        r"\bmodel are you using\b",
        r"\bwhich ai\b",
        r"\bwhat ai\b",
        r"\bare you gpt\b",
        r"\bare you chatgpt\b",
        r"\bpowered by openai\b",
        r"\bwho made you\b",
        r"\bwhich provider\b",
        r"\bwhat provider\b",
    )
    return any(re.search(pattern, text) for pattern in patterns)


def _identity_answer() -> dict:
    """Return a safe, fixed response without disclosing internal configuration."""
    return {
        "answer": (
            "I’m Aura Merchandising Copilot, a retail decision-support "
            "assistant. I can help with product inventory, sales analysis, "
            "forecasts, and promotion recommendations, but I cannot disclose "
            "internal model or provider configuration."
        ),
        "retrieved_sources": [],
        "provider": "configuration-protected",
        "grounding_note": (
            "This response was generated by a deterministic server-side "
            "rule without calling an AI provider."
        ),
    }


def _generate_with_provider(provider, message, payload):
    """Generate an answer using one configured AI provider."""
    context_json = json.dumps(payload, ensure_ascii=False, default=str)

    if provider == "groq":
        if not config.GROQ_API_KEY:
            raise RuntimeError("Groq API key is not configured.")
        from groq import Groq
        client = Groq(api_key=config.GROQ_API_KEY)
        response = client.chat.completions.create(
            model=config.GROQ_MODEL,
            messages=[
                {"role": "system", "content": SYSTEM_INSTRUCTIONS},
                {"role": "user", "content": f"User request:\n{message}\n\nVerified business context and knowledge:\n{context_json}"},
            ],
            temperature=0.1,
            max_tokens=1000,
        )
        answer = (response.choices[0].message.content or "").strip()

    elif provider == "gemini":
        if not config.GEMINI_API_KEY:
            raise RuntimeError("Gemini API key is not configured.")
        from google import genai
        from google.genai import types
        client = genai.Client(api_key=config.GEMINI_API_KEY)
        response = client.models.generate_content(
            model=config.GEMINI_MODEL,
            contents=f"{SYSTEM_INSTRUCTIONS}\n\nUser request:\n{message}\n\nVerified business context and knowledge:\n{context_json}",
            config=types.GenerateContentConfig(temperature=0.1, max_output_tokens=1000),
        )
        answer = (response.text or "").strip()
    else:
        raise ValueError(f"Unsupported AI provider: {provider}")

    if not answer:
        raise RuntimeError(f"{provider} returned an empty response.")
    return answer


def grounded_answer(message: str, structured_context: dict):
    # Identity questions are answered from config so the LLM cannot invent a model name.
    if _is_model_identity_question(message):
        return _identity_answer()

    docs = retrieve_knowledge(message)
    payload = {
        "user_question": message,
        "verified_context": structured_context,
        "retrieved_knowledge": [{"source": doc["source"], "content": doc["content"]} for doc in docs],
    }

    answer = ""
    provider_used = "deterministic-fallback"
    trace_status = "not_started"
    langfuse = None

    try:
        from langfuse import get_client
        langfuse = get_client()
        observation_context = langfuse.start_as_current_observation(
            as_type="span",
            name="aura-copilot-answer",
            input=payload,
            metadata={"application": "Aura Merchandising Copilot", "operation": "AI Assistant chat"},
        )
    except Exception:
        logger.exception("Could not initialize Langfuse observation")
        observation_context = nullcontext(None)
        langfuse = None

    try:
        with observation_context as trace:
            preferred = str(getattr(config, "LLM_PROVIDER", "groq")).strip().lower()
            if preferred not in ("groq", "gemini"):
                preferred = "groq"
            providers = [preferred, "gemini" if preferred == "groq" else "groq"]
            failures = []

            for provider in providers:
                try:
                    if provider == "groq" and not config.GROQ_API_KEY:
                        logger.warning("Groq skipped: API key is not configured.")
                        continue
                    if provider == "gemini" and not config.GEMINI_API_KEY:
                        logger.warning("Gemini skipped: API key is not configured.")
                        continue
                    answer = _generate_with_provider(provider, message, payload)
                    provider_used = provider
                    trace_status = "completed"
                    logger.info("Aura answer generated successfully using %s.", provider)
                    break
                except Exception as exc:
                    failures.append(f"{provider}: {type(exc).__name__}")
                    logger.exception("AI generation failed using %s.", provider)

            if not answer:
                provider_used = "fallback"
                trace_status = "error"
                answer = (
                    "### AI assistant temporarily unavailable\n\n"
                    "I could not obtain a valid response from either configured AI provider.\n\n"
                    "**What you can do now**\n"
                    "- Retry your question in a moment.\n"
                    "- Open the Promotion Optimizer and select the SKU to calculate promotion scenarios from the workbook.\n"
                    "- Check the FastAPI terminal for the provider error.\n\n"
                    "No new discount, sales forecast, or profit figure has been assumed."
                )
                logger.error("Both AI providers failed or were unavailable. Failure count: %s", len(failures))

            if trace:
                try:
                    trace.update(output={"answer": answer}, metadata={"provider": provider_used, "status": trace_status})
                except Exception:
                    logger.exception("Could not update Langfuse observation")
    except Exception:
        logger.exception("Unexpected chat or tracing failure")
        if not answer:
            answer = "The AI assistant encountered an unexpected error. Please retry or use the Promotion Optimizer."
        provider_used = "fallback"
    finally:
        if langfuse:
            try:
                langfuse.flush()
            except Exception:
                logger.exception("Langfuse flush failed")

    return {
        "answer": answer,
        "retrieved_sources": [doc["source"] for doc in docs],
        "provider": provider_used,
        "grounding_note": "The response uses supplied structured context and retrieved local documents. Estimates should be validated before business use.",
    }
